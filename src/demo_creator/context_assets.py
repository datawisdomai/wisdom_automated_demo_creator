"""Context reaches the Wisdom domain ONLY through the context extractor.

The demo's structured definitions (metrics.csv, reviewed_queries.py, knowledge.csv, the
bootstrap's knowledge sections) stay local as the source of truth for `rq-check`,
`metrics-check` and the eval set. For the domain they are rendered into assets that look
like what a real data team owns — a dbt semantic-layer YAML, a certified query library
`.sql`, an analyst handbook export — and uploaded to the extractor next to the authored
`context_assets[]` (glossary, standards, wiki pages, chat exports, memos). After the run
`coverage()` reads back what the domain actually has and reports the gaps; nothing is
pushed through the CSV / direct-API path in `context_mode: extractor` (the default).

Verified on proddemo 2026-10-13: the extractor registers .yml/.yaml/.sql/.txt/.csv/.pdf
(not .md); DomainKnowledgeAgentType covers METRICS, REVIEWED_QUERIES, CONTEXT, SYNONYMS,
DESCRIPTIONS; suggestions arrive as modeling suggestions that must be accepted.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from difflib import SequenceMatcher
from pathlib import Path

from .context_files import Metric, bootstrap_sections, bootstrap_to_knowledge, read_knowledge_csv, read_metrics_csv
from .spec import DemoSpec

# agent types the extractor runs for the generated + authored assets
ALL_AGENTS = ["CONTEXT", "DESCRIPTIONS", "SYNONYMS", "METRICS", "REVIEWED_QUERIES", "SKILL"]

# which suggestion families the pipeline accepts automatically after an extraction run
ACCEPT_DEFAULT = ["knowledge", "synonyms", "metrics", "reviewed_queries", "skills"]   # descriptions stay pending (steward review beat)


@dataclass(frozen=True)
class ExtractionFile:
    path: Path
    kind: str           # semantic_model | query_library | handbook | <authored kind>
    instructions: str   # file-level guidance for the extractor
    generated: bool
    source: Path | None = None   # the authored markdown/text the file was rendered from (its digest decides re-uploads)

    @property
    def digest_path(self) -> Path:
        return self.source if self.source is not None else self.path


# ---------------------------------------------------------------- helpers
def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def _yaml_str(s: str) -> str:
    """Double-quoted YAML scalar."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


_AGG = re.compile(r"^\s*(SUM|COUNT|AVG|MIN|MAX)\s*\(\s*(?:DISTINCT\s+)?([A-Z_][A-Z0-9_]*)\.([A-Z_][A-Z0-9_]*)\s*\)\s*$", re.I)


def _views_used(metrics: list[Metric]) -> dict[str, list[Metric]]:
    out: dict[str, list[Metric]] = {}
    for m in metrics:
        if m.view:
            out.setdefault(m.view, []).append(m)
    return out


# ---------------------------------------------------------------- renderers
def render_semantic_model(spec: DemoSpec, metrics: list[Metric]) -> str:
    """A dbt-style semantic layer file: one semantic model per view (entities, dimensions
    inferred from the DDL comments are left to DESCRIPTIONS), measures for the simple
    aggregates, and a `metrics:` list carrying every certified metric with its exact SQL
    expression in `meta.sql_expression` so the METRICS agent can create it verbatim."""
    db = spec.snowflake.database
    schema = spec.snowflake.schema
    lines = [
        f"# {spec.title} — certified semantic layer (dbt MetricFlow)",
        f"# Generated by analytics engineering for {db}.{schema}. Every metric below is certified;",
        "# the SQL in meta.sql_expression is the definition of record and must be used verbatim.",
        f"# Demo as-of date {spec.as_of.isoformat()}.",
        "",
        "version: 2",
        "",
        "semantic_models:",
    ]
    for view, ms in _views_used(metrics).items():
        lines += [
            f"  - name: {view.lower()}",
            f"    description: {_yaml_str('Certified view ' + db + '.' + schema + '.' + view)}",
            f"    model: ref('{view.lower()}')",
            "    defaults:",
            "      agg_time_dimension: as_of_date",
            "    measures:",
        ]
        seen = set()
        for m in ms:
            mm = _AGG.match(m.sql)
            if not mm:
                continue
            agg, _, col = mm.groups()
            key = (agg.lower(), col.lower())
            if key in seen:
                continue
            seen.add(key)
            lines += [
                f"      - name: {agg.lower()}_{col.lower()}",
                f"        agg: {'count_distinct' if 'DISTINCT' in m.sql.upper() else agg.lower()}",
                f"        expr: {col}",
                f"        description: {_yaml_str(m.description)}",
            ]
        if not seen:
            lines[-1] = "    measures: []"
    lines += ["", "metrics:"]
    for m in metrics:
        mm = _AGG.match(m.sql)
        lines += [
            f"  - name: {m.name}",
            f"    label: {_yaml_str(m.name.replace('_', ' ').title())}",
            f"    description: {_yaml_str(m.description)}",
            f"    type: {'simple' if mm else 'derived'}",
            "    type_params:",
        ]
        if mm:
            agg, _, col = mm.groups()
            lines.append(f"      measure: {agg.lower()}_{col.lower()}")
        else:
            lines.append(f"      expr: {_yaml_str(m.sql)}")
        lines += [
            "    meta:",
            "      certified: true",
            f"      database: {m.database or db}",
            f"      source_view: {m.view or ''}",
            f"      sql_expression: {_yaml_str(m.sql)}",
        ]
    lines.append("")
    return "\n".join(lines)


def library_queries(registry):
    """Reviewed queries that go into the certified query library: everything not tagged
    `eval_only` (those stay in the eval set and rq-check but are left out to keep the
    extractor's file small) and nothing with a `source` (federated SQL runs on another
    connection; the publish step binds it directly)."""
    return [q for q in (registry or [])
            if "eval_only" not in (getattr(q, "tags", ()) or ()) and not getattr(q, "source", None)]


def render_query_library(spec: DemoSpec, registry) -> str:
    """A certified query library as analysts keep it in the analytics repo: one block per
    question with the approved SQL. The REVIEWED_QUERIES agent turns each block into a
    reviewed query (question verbatim, SQL verbatim)."""
    db, schema = spec.snowflake.database, spec.snowflake.schema
    lines = [
        f"-- {spec.title} — certified query library",
        f"-- Repository: analytics/queries/{_slug(spec.name)}_certified_queries.sql",
        f"-- Warehouse: Snowflake {db}.{schema} (dialect snowflake). Demo as-of date {spec.as_of.isoformat()}.",
        "-- Each block is a business question and the SQL the data stewards certified for it.",
        "-- Keep the question text and the SQL together; both are reviewed and must not be edited independently.",
        "",
    ]
    for i, q in enumerate(library_queries(registry), 1):
        sql = q.sql.strip().rstrip(";")
        tags = ", ".join(getattr(q, "tags", ()) or ()) or "certified"
        lines += [
            "-- " + "-" * 76,
            f"-- name: q{i:03d}_{_slug(q.nl)[:60]}",
            f"-- question: {q.nl}",
            f"-- tags: {tags} | owner: data stewards | certified: yes",
            sql + ";",
            "",
        ]
    return "\n".join(lines)


def render_handbook(spec: DemoSpec, facts: list[str]) -> str:
    """An analyst handbook export (the kind of page a team keeps in Confluence): numbered
    working notes carrying the story facts and the bootstrap's knowledge sections."""
    lines = [
        f"{spec.title} — Analytics Team Handbook (wiki export)",
        f"Page: Analytics / Handbook / Working notes for {spec.snowflake.database}.{spec.snowflake.schema}",
        f"Last reviewed: {spec.as_of.isoformat()} by the data stewards. Audience: analysts, Finance, Sales Ops, the AI assistant.",
        "",
        "How to use this page: every note below is a fact the stewards have confirmed against the certified",
        "views. If a report or an answer contradicts one of them, the note wins until the stewards change it.",
        "",
        "WORKING NOTES",
        "",
    ]
    for i, f in enumerate(facts, 1):
        lines.append(f"{i}. {f}")
        lines.append("")
    return "\n".join(lines)


def generated_dir(spec: DemoSpec) -> Path:
    d = spec.paths.build / "context"
    d.mkdir(parents=True, exist_ok=True)
    return d


def render_generated_assets(spec: DemoSpec, registry) -> list[ExtractionFile]:
    """Write the generated assets to build/context/ and describe them for the extractor."""
    out = generated_dir(spec)
    slug = _slug(spec.name)
    files: list[ExtractionFile] = []

    metrics = read_metrics_csv(spec.metrics_path) if spec.metrics_path.is_file() else []
    if metrics:
        p = out / f"{slug}_semantic_models.yml"
        p.write_text(render_semantic_model(spec, metrics))
        files.append(ExtractionFile(p, "semantic_model", (
            "This is the certified dbt semantic layer for the warehouse schema. Every entry under 'metrics:' is a certified "
            "business metric: create one domain metric per entry, named exactly as 'name', with the SQL aggregate expression "
            "given verbatim in meta.sql_expression over the view named in meta.source_view, and use 'description' as its "
            "description. Do not invent additional metrics."), True))

    if registry is not None and len(registry):
        p = out / f"{slug}_certified_queries.sql"
        p.write_text(render_query_library(spec, registry))
        files.append(ExtractionFile(p, "query_library", (
            "This is the analytics team's certified query library. Each block is one business question ('-- question:') with "
            "the SQL the stewards certified for it. Create one reviewed query per block: the question text verbatim as the "
            "question and the SQL statement verbatim as the answer (Snowflake dialect). Do not merge or rewrite blocks."), True))

    facts: list[str] = []
    if spec.knowledge_path.is_file():
        facts += read_knowledge_csv(spec.knowledge_path)
    if spec.bootstrap_path.is_file():
        facts += [f for f in bootstrap_to_knowledge(spec.bootstrap_path.read_text()) if f not in facts]
    if facts:
        p = out / f"{slug}_analyst_handbook.txt"
        p.write_text(render_handbook(spec, facts))
        files.append(ExtractionFile(p, "handbook", (
            "This is the analytics team's handbook of confirmed working notes. Capture each numbered note as a knowledge "
            "entry in its own words, including the dates, names, thresholds and column or view names it mentions."), True))
    return files


# context_assets[] kinds that are uploaded as the text file itself (the extractor registers .sql/.txt),
# with the extension the extractor expects; everything else is rendered to PDF by `demo docs`.
TEXT_KINDS = {"query_log": ".sql", "report_definition": ".txt", "sql": ".sql", "text": ".txt"}


def asset_output_path(spec: DemoSpec, asset: dict) -> Path:
    """Where `demo docs` puts this asset for the extractor: build/docs/<stem>.pdf, or
    build/docs/<stem><ext> for the text kinds."""
    stem = Path(asset["spec"]).stem
    ext = TEXT_KINDS.get(str(asset.get("kind") or ""), ".pdf")
    return spec.paths.docs_out / (stem + ext)


def authored_assets(spec: DemoSpec) -> list[ExtractionFile]:
    """The `context_assets[]` files produced by `demo docs` (PDFs, or the text file for the text kinds)."""
    files = []
    for a in list(spec.raw.get("context_assets") or []):
        pdf = asset_output_path(spec, a)
        kind = a.get("kind", "document")
        instr = a.get("instructions") or {
            "standard": "A metric definitions standard: capture every definition, measurement rule, owner and physical mapping as knowledge; create synonyms for the alternate names it lists.",
            "glossary": "A business glossary and ownership register: capture each term's definition, owner, steward, source system and physical asset as knowledge, and the synonym lists as synonyms; use the physical asset mappings to describe tables and columns.",
            "wiki": "A data platform wiki page: capture the join paths, gotchas, refresh cadence and lineage as knowledge and improve table and column descriptions from it.",
            "chat_export": "A chat channel export in which data stewards answer analysts' questions: capture each answered question as knowledge in the steward's words.",
            "query_log": ("A query-log export from the production data warehouse (one logged SQL statement per block with its user, timestamp and CPU time). "
                          "Many statements are noise (statistics collection, session checks, ETL audit, unrelated schemas): ignore those. For every business "
                          "statement that reads the analytics views, create a reviewed query whose question is what a business user would have asked in plain "
                          "language and whose SQL is the statement rewritten for this warehouse's dialect against the same views; capture recurring filters, "
                          "groupings and formulas as knowledge and the column aliases as synonyms."),
            "report_definition": ("A BI report definition export (attributes, metrics with formulas, filters, drill paths). Capture every metric formula and "
                                  "business rule as knowledge, each attribute's alternate names as synonyms, and the report's main grid as a reviewed query."),
            "runbook": ("A team runbook of repeatable analysis procedures. Turn each procedure into a skill: a lowercase hyphenated name, a one-sentence "
                        "description of when to use it, and the procedure's steps, data rules and presentation rules as the instructions, kept verbatim. "
                        "Capture the definitions it states as knowledge."),
        }.get(kind, "A business document: capture the facts, dates, names and numbers it states as knowledge.")
        files.append(ExtractionFile(pdf, kind, instr, False, source=spec.dir / a["spec"]))
    return files


def extraction_files(spec: DemoSpec, registry) -> list[ExtractionFile]:
    return render_generated_assets(spec, registry) + authored_assets(spec)


# ---------------------------------------------------------------- read-back
def _norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", (s or "").lower()).strip()


def _match(wanted: list[str], have: list[str], *, threshold: float = 0.9) -> tuple[list[str], list[str]]:
    hv = [_norm(h) for h in have]
    found, missing = [], []
    for w in wanted:
        nw = _norm(w)
        if nw in hv or any(SequenceMatcher(None, nw, h).ratio() >= threshold for h in hv):
            found.append(w)
        else:
            missing.append(w)
    return found, missing


def coverage(client, domain_id: str, spec: DemoSpec, registry) -> dict:
    """What the domain actually holds versus what the assets carried."""
    out: dict = {}
    metrics = read_metrics_csv(spec.metrics_path) if spec.metrics_path.is_file() else []
    have_m = [m.get("name", "") for m in client.list_metrics(domain_id)]
    f, miss = _match([m.name for m in metrics], have_m, threshold=0.95)
    out["metrics"] = {"expected": len(metrics), "found": len(f), "missing": miss, "in_domain": len(have_m)}
    have_q = [str(r.get("question", "")) for r in client.list_reviewed_queries(domain_id, limit=500)]
    wanted_q = [q.nl for q in library_queries(registry)] if registry is not None else []
    f, miss = _match(wanted_q, have_q, threshold=0.85)
    out["reviewed_queries"] = {"expected": len(wanted_q), "found": len(f), "missing": miss, "in_domain": len(have_q)}
    facts = read_knowledge_csv(spec.knowledge_path) if spec.knowledge_path.is_file() else []
    out["knowledge"] = {"story_facts": len(facts), "in_domain": len(client.get_domain_knowledge(domain_id))}
    wanted_s = [sk.name for sk in spec.wisdom.skills]
    if wanted_s:
        try:
            have_s = [str(x.get("name", "")) for x in client.list_domain_skills(domain_id, include_markdown=False)]
        except Exception:  # noqa: BLE001 — an older deployment without skills
            have_s = []
        f, miss = _match(wanted_s, have_s, threshold=0.95)
        out["skills"] = {"expected": len(wanted_s), "found": len(f), "missing": miss, "in_domain": len(have_s)}

    def pct(d):
        return round(d["found"] / d["expected"], 3) if d["expected"] else 1.0
    out["metrics"]["coverage"] = pct(out["metrics"])
    out["reviewed_queries"]["coverage"] = pct(out["reviewed_queries"])
    return out


def accept_suggestions(client, domain_id: str, families: list[str], *, job_run_ids: list[str] | None = None,
                       exclude_ids: set[str] | None = None) -> dict:
    """Accept pending modeling suggestions of the requested families; leave the rest
    (table / column description rewrites by default) pending for steward review.

    `job_run_ids` scopes the candidates to the suggestions produced by those extraction runs
    (falls back to the whole domain when the filter yields nothing); `exclude_ids` are never
    accepted whatever the filter does — on a shared domain they are the suggestions that were
    pending before this demo uploaded anything."""
    def family(s: dict) -> str | None:
        t = s.get("task") or {}
        typ = str(t.get("type") or "")
        if t.get("addLearnedMetric") or "METRIC" in typ:
            return "metrics"
        if t.get("addReviewedQuery") or "REVIEWED_QUERY" in typ:
            return "reviewed_queries"
        if t.get("addLearnedKnowledge") or typ == "ADD_LEARNED_KNOWLEDGE":
            return "knowledge"
        if "SYNONYM" in typ:
            return "synonyms"
        if t.get("upsertSkill") or "SKILL" in typ:
            return "skills"
        if "DESCRIPTION" in typ or t.get("addColumnDescription") or t.get("enterTableDescription"):
            return "descriptions"
        return None

    nodes: dict[str, dict] = {}
    scoped = False
    for rid in job_run_ids or []:
        for s in client.modeling_suggestions(domain_id, include_all_statuses=True, job_run_id=rid):
            nodes[s["id"]] = s
    if nodes:
        scoped = True
    else:
        nodes = {s["id"]: s for s in client.modeling_suggestions(domain_id, include_all_statuses=True)}
    exclude = set(exclude_ids or ())
    pending = [s for s in nodes.values() if "PENDING" in str(s.get("status", "")) and s["id"] not in exclude]
    todo = [s["id"] for s in pending if family(s) in families]
    accepted = failed = 0
    accepted_ids: list[str] = []
    errors: list[str] = []
    for i in range(0, len(todo), 20):
        chunk = todo[i:i + 20]
        for j, r in enumerate(client.apply_modeling_suggestions(domain_id, chunk)):
            if r.get("success"):
                accepted += 1
                accepted_ids.append(str(r.get("id") or (chunk[j] if j < len(chunk) else "")))
            else:
                failed += 1
                if len(errors) < 5:
                    errors.append(str(r.get("errorMessage"))[:120])
    left = len(pending) - accepted
    by_family: dict[str, int] = {}
    for s in pending:
        by_family[family(s) or "other"] = by_family.get(family(s) or "other", 0) + 1
    return {"pending_before": len(pending), "by_family": by_family, "accepted": accepted, "failed": failed, "left_pending": left, "errors": errors,
            "accepted_ids": [a for a in accepted_ids if a], "scoped": scoped, "excluded": len(exclude)}
