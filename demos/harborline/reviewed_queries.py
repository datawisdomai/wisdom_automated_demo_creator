"""Reviewed NL -> SQL pairs for the Harborline Private Capital demo.

`demo rq-check harborline --snowflake` executes every pair against DuckDB and
Snowflake and writes build/reviewed-queries.csv in Wisdom's import format.
NL text must not contain commas; SQL is portable (ANSI CASE, DATE literals).
Queries tagged eval_only stay in rq-check and the eval set but out of the
certified query library the context extractor receives (keeps the file small).
"""
from demo_creator.reviewed_queries import Registry

rq = Registry()
add = rq.add


def add_eval_only(nl, sql):
    rq.add(nl, sql, tags=("eval_only",))


LATEST = "DATE '2026-06-30'"
HERO = "Calder Ridge Capital Partners IV"
WESTBROOK = "Westbrook State Retirement System"

# ---------------------------------------------------------------- lookups
add("Which Harborline indices are published and what does each one cover?",
    "SELECT BENCHMARK_ID, BENCHMARK_NAME, STRATEGY, REGION, CONSTITUENT_RULE, IS_BROAD_INDEX FROM BENCHMARKS ORDER BY IS_BROAD_INDEX DESC, BENCHMARK_ID")
add("How many funds do we cover by strategy and region?",
    "SELECT STRATEGY, REGION, COUNT(*) AS FUNDS, ROUND(SUM(FUND_SIZE_USD_M), 0) AS COMMITMENTS_USD_M FROM FUNDS GROUP BY STRATEGY, REGION ORDER BY STRATEGY, FUNDS DESC")
add(f"Show me {HERO} and its latest performance.",
    f"SELECT FUND_ID, FUND_NAME, MANAGER_NAME, STRATEGY, REGION, VINTAGE_YEAR, FUND_SIZE_USD_M, SIZE_BUCKET, USES_SUBSCRIPTION_LINE, SUBSCRIPTION_LINE_LIMIT_USD_M, QUARTER_END, NAV_USD_M, CUMULATIVE_CALLED_USD_M, CUMULATIVE_DISTRIBUTED_USD_M, PAID_IN_PCT, CREDIT_LINE_BALANCE_USD_M, CREDIT_LINE_PCT_OF_NAV, IRR_SINCE_INCEPTION_PCT, TVPI, DPI, RVPI FROM V_FUND_PERFORMANCE_LATEST WHERE FUND_NAME = '{HERO}'")
add("Which allocators are on the portal and what tier is each on?",
    "SELECT ALLOCATOR_ID, ALLOCATOR_NAME, ALLOCATOR_TYPE, HEADQUARTERS, TOTAL_PC_COMMITMENT_USD_M, PORTAL_TIER FROM ALLOCATORS ORDER BY TOTAL_PC_COMMITMENT_USD_M DESC")
add("How many funds use a subscription credit line by vintage year?",
    "SELECT VINTAGE_YEAR, COUNT(*) AS FUNDS, SUM(CASE WHEN USES_SUBSCRIPTION_LINE THEN 1 ELSE 0 END) AS FUNDS_WITH_LINE, ROUND(100.0 * SUM(CASE WHEN USES_SUBSCRIPTION_LINE THEN 1 ELSE 0 END) / COUNT(*), 1) AS PCT_WITH_LINE, ROUND(SUM(SUBSCRIPTION_LINE_LIMIT_USD_M), 0) AS TOTAL_LINE_LIMIT_USD_M FROM FUNDS GROUP BY VINTAGE_YEAR ORDER BY VINTAGE_YEAR")

# ---------------------------------------------------------------- CP1: the custom index
COHORT = "c.STRATEGY = 'Buyout' AND c.REGION = 'North America' AND c.VINTAGE_YEAR BETWEEN 2015 AND 2020"
add("Build a custom index of North American buyout funds with vintages 2015 to 2020 and show its median IRR by quarter against the Harborline Broad Private Equity Index.",
    f"""SELECT c.QUARTER_END, COUNT(c.FUND_ID) AS FUND_COUNT, ROUND(MEDIAN(c.IRR_SINCE_INCEPTION_PCT), 2) AS COHORT_MEDIAN_IRR_PCT,
       b.POOLED_IRR_PCT AS BROAD_PE_INDEX_IRR_PCT, ROUND(MEDIAN(c.IRR_SINCE_INCEPTION_PCT) - b.POOLED_IRR_PCT, 2) AS GAP_PTS
FROM V_FUND_PERFORMANCE_QUARTERLY c
JOIN V_BENCHMARK_QUARTERLY b ON b.QUARTER_END = c.QUARTER_END AND b.BENCHMARK_ID = 'HPCI-BROAD-PE' AND b.VINTAGE_YEAR IS NULL
WHERE {COHORT}
GROUP BY c.QUARTER_END, b.POOLED_IRR_PCT
ORDER BY c.QUARTER_END""")
add("What are the latest fund count median IRR and pooled TVPI of North American buyout funds with vintages 2015 to 2020 compared with the Harborline Broad Private Equity Index?",
    f"""SELECT COUNT(c.FUND_ID) AS FUND_COUNT, ROUND(MEDIAN(c.IRR_SINCE_INCEPTION_PCT), 2) AS COHORT_MEDIAN_IRR_PCT,
       ROUND(SUM(c.NAV_USD_M + c.CUMULATIVE_DISTRIBUTED_USD_M) / SUM(c.CUMULATIVE_CALLED_USD_M), 3) AS COHORT_POOLED_TVPI,
       b.POOLED_IRR_PCT AS BROAD_PE_INDEX_IRR_PCT, b.POOLED_TVPI AS BROAD_PE_INDEX_TVPI,
       ROUND(MEDIAN(c.IRR_SINCE_INCEPTION_PCT) - b.POOLED_IRR_PCT, 2) AS IRR_GAP_PTS
FROM V_FUND_PERFORMANCE_LATEST c
JOIN V_BENCHMARK_QUARTERLY b ON b.QUARTER_END = {LATEST} AND b.BENCHMARK_ID = 'HPCI-BROAD-PE' AND b.VINTAGE_YEAR IS NULL
WHERE {COHORT} AND c.QUARTER_END = {LATEST}
GROUP BY b.POOLED_IRR_PCT, b.POOLED_TVPI""")
add("Split the North American buyout 2015 to 2020 custom index by fund size bucket and compare median IRR and pooled TVPI.",
    f"""SELECT c.SIZE_BUCKET, COUNT(c.FUND_ID) AS FUND_COUNT, ROUND(SUM(c.FUND_SIZE_USD_M), 0) AS COMMITMENTS_USD_M,
       ROUND(MEDIAN(c.IRR_SINCE_INCEPTION_PCT), 2) AS MEDIAN_IRR_PCT,
       ROUND(SUM(c.NAV_USD_M + c.CUMULATIVE_DISTRIBUTED_USD_M) / SUM(c.CUMULATIVE_CALLED_USD_M), 3) AS POOLED_TVPI,
       ROUND(SUM(c.CUMULATIVE_DISTRIBUTED_USD_M) / SUM(c.CUMULATIVE_CALLED_USD_M), 3) AS POOLED_DPI
FROM V_FUND_PERFORMANCE_LATEST c
WHERE {COHORT} AND c.QUARTER_END = {LATEST}
GROUP BY c.SIZE_BUCKET
ORDER BY MEDIAN_IRR_PCT DESC""")
add("Show the cash-flow pacing of North American buyout funds with vintages 2015 to 2020 by fund age as a percent of commitments.",
    f"""SELECT c.FUND_AGE_QUARTERS, COUNT(c.FUND_ID) AS FUND_COUNT,
       ROUND(100.0 * SUM(c.CALLS_USD_M) / SUM(c.FUND_SIZE_USD_M), 2) AS CALLS_PCT_OF_COMMITMENT,
       ROUND(100.0 * SUM(c.DISTRIBUTIONS_USD_M) / SUM(c.FUND_SIZE_USD_M), 2) AS DISTRIBUTIONS_PCT_OF_COMMITMENT,
       ROUND(100.0 * SUM(c.NET_CASH_FLOW_USD_M) / SUM(c.FUND_SIZE_USD_M), 2) AS NET_CASH_FLOW_PCT_OF_COMMITMENT,
       ROUND(AVG(c.PAID_IN_PCT), 1) AS AVG_PAID_IN_PCT, ROUND(MEDIAN(c.DPI), 3) AS MEDIAN_DPI
FROM V_CASH_FLOW_PACING_QUARTERLY c
WHERE {COHORT}
GROUP BY c.FUND_AGE_QUARTERS
ORDER BY c.FUND_AGE_QUARTERS""")
add_eval_only("How does the North American buyout 2015 to 2020 cohort compare with the HPCI-BUYOUT-NA index by vintage year at the latest quarter?",
    f"""SELECT c.VINTAGE_YEAR, COUNT(c.FUND_ID) AS FUND_COUNT, ROUND(MEDIAN(c.IRR_SINCE_INCEPTION_PCT), 2) AS MEDIAN_IRR_PCT, b.POOLED_IRR_PCT AS INDEX_POOLED_IRR_PCT, b.POOLED_TVPI AS INDEX_POOLED_TVPI
FROM V_FUND_PERFORMANCE_LATEST c
JOIN V_BENCHMARK_QUARTERLY b ON b.BENCHMARK_ID = 'HPCI-BUYOUT-NA' AND b.VINTAGE_YEAR = c.VINTAGE_YEAR AND b.QUARTER_END = c.QUARTER_END
WHERE {COHORT} AND c.QUARTER_END = {LATEST}
GROUP BY c.VINTAGE_YEAR, b.POOLED_IRR_PCT, b.POOLED_TVPI
ORDER BY c.VINTAGE_YEAR""")

# ---------------------------------------------------------------- CP2: subscription lines and the hero report
add("Do funds that use a subscription line show higher IRR early in life? Compare vintages 2019 to 2022 at 4 8 12 and 16 quarters of age.",
    """SELECT FUND_AGE_QUARTERS, SUM(FUNDS_WITH_LINE) AS FUNDS_WITH_LINE, SUM(FUNDS_WITHOUT_LINE) AS FUNDS_WITHOUT_LINE,
       ROUND(SUM(AVG_IRR_WITH_LINE_PCT * FUNDS_WITH_LINE) / NULLIF(SUM(FUNDS_WITH_LINE), 0), 2) AS AVG_IRR_WITH_LINE_PCT,
       ROUND(SUM(AVG_IRR_WITHOUT_LINE_PCT * FUNDS_WITHOUT_LINE) / NULLIF(SUM(FUNDS_WITHOUT_LINE), 0), 2) AS AVG_IRR_WITHOUT_LINE_PCT,
       ROUND(SUM(AVG_IRR_WITH_LINE_PCT * FUNDS_WITH_LINE) / NULLIF(SUM(FUNDS_WITH_LINE), 0) - SUM(AVG_IRR_WITHOUT_LINE_PCT * FUNDS_WITHOUT_LINE) / NULLIF(SUM(FUNDS_WITHOUT_LINE), 0), 2) AS IRR_GAP_PTS
FROM V_SUBSCRIPTION_LINE_IRR_GAP
WHERE VINTAGE_YEAR BETWEEN 2019 AND 2022 AND FUND_AGE_QUARTERS IN (4, 8, 12, 16)
GROUP BY FUND_AGE_QUARTERS
ORDER BY FUND_AGE_QUARTERS""")
add("Has the subscription line IRR gap closed for mature vintages 2014 to 2017 at the latest quarter?",
    f"""SELECT VINTAGE_YEAR, SUM(CASE WHEN USES_SUBSCRIPTION_LINE THEN 1 ELSE 0 END) AS FUNDS_WITH_LINE, SUM(CASE WHEN USES_SUBSCRIPTION_LINE THEN 0 ELSE 1 END) AS FUNDS_WITHOUT_LINE,
       ROUND(AVG(CASE WHEN USES_SUBSCRIPTION_LINE THEN IRR_SINCE_INCEPTION_PCT END), 2) AS AVG_IRR_WITH_LINE_PCT,
       ROUND(AVG(CASE WHEN USES_SUBSCRIPTION_LINE THEN NULL ELSE IRR_SINCE_INCEPTION_PCT END), 2) AS AVG_IRR_WITHOUT_LINE_PCT,
       ROUND(AVG(CASE WHEN USES_SUBSCRIPTION_LINE THEN IRR_SINCE_INCEPTION_PCT END) - AVG(CASE WHEN USES_SUBSCRIPTION_LINE THEN NULL ELSE IRR_SINCE_INCEPTION_PCT END), 2) AS IRR_GAP_PTS
FROM V_FUND_PERFORMANCE_LATEST
WHERE VINTAGE_YEAR BETWEEN 2014 AND 2017 AND QUARTER_END = {LATEST}
GROUP BY VINTAGE_YEAR
ORDER BY VINTAGE_YEAR""")
add("Which funds have a subscription line balance above 15 percent of NAV at the latest quarter?",
    f"""SELECT FUND_NAME, MANAGER_NAME, STRATEGY, REGION, VINTAGE_YEAR, NAV_USD_M, CREDIT_LINE_BALANCE_USD_M, CREDIT_LINE_PCT_OF_NAV, SUBSCRIPTION_LINE_LIMIT_USD_M, IRR_SINCE_INCEPTION_PCT
FROM V_FUND_PERFORMANCE_LATEST
WHERE QUARTER_END = {LATEST} AND CREDIT_LINE_PCT_OF_NAV > 15
ORDER BY CREDIT_LINE_PCT_OF_NAV DESC""")
add(f"What did {HERO} call and distribute in Q2 2026 and what is its subscription line balance?",
    f"""SELECT p.FUND_NAME, p.QUARTER_END, p.CALLS_USD_M, p.DISTRIBUTIONS_USD_M, p.NET_CASH_FLOW_USD_M, p.CUMULATIVE_CALLED_USD_M, p.CUMULATIVE_DISTRIBUTED_USD_M, p.PAID_IN_PCT, p.NAV_USD_M, p.CREDIT_LINE_BALANCE_USD_M, p.DPI
FROM V_CASH_FLOW_PACING_QUARTERLY p
WHERE p.FUND_NAME = '{HERO}' AND p.QUARTER_END = {LATEST}""")
add(f"Does the figure extracted from the {HERO} Q2 2026 quarterly report match the published NAV?",
    f"""SELECT FUND_NAME, REPORT_QUARTER_END, SOURCE_DOCUMENT, EXTRACTED_NAV_USD_M, PUBLISHED_NAV_USD_M, NAV_VARIANCE_USD_M, EXTRACTED_CALLS_IN_QUARTER_USD_M, PUBLISHED_CALLS_IN_QUARTER_USD_M, EXTRACTED_DISTRIBUTIONS_IN_QUARTER_USD_M, PUBLISHED_DISTRIBUTIONS_IN_QUARTER_USD_M, EXTRACTED_CREDIT_LINE_BALANCE_USD_M, PUBLISHED_CREDIT_LINE_BALANCE_USD_M, EXTRACTION_CONFIDENCE, REVIEW_STATUS, MATCHES_PUBLISHED
FROM V_REPORT_EXTRACTION_RECONCILIATION
WHERE FUND_NAME = '{HERO}' AND REPORT_QUARTER_END = {LATEST}""")
add_eval_only(f"Show the quarterly NAV IRR and credit line balance history of {HERO} since 2024.",
    f"""SELECT QUARTER_END, FUND_AGE_QUARTERS, NAV_USD_M, CUMULATIVE_CALLED_USD_M, CUMULATIVE_DISTRIBUTED_USD_M, CREDIT_LINE_BALANCE_USD_M, CREDIT_LINE_PCT_OF_NAV, IRR_SINCE_INCEPTION_PCT, TVPI, DPI, QUARTERLY_RETURN_PCT
FROM V_FUND_PERFORMANCE_QUARTERLY
WHERE FUND_NAME = '{HERO}' AND QUARTER_END >= DATE '2024-01-01'
ORDER BY QUARTER_END""")
add("How many quarterly report extractions need analyst review and what is the average confidence by review status?",
    """SELECT REVIEW_STATUS, COUNT(*) AS EXTRACTIONS, ROUND(AVG(EXTRACTION_CONFIDENCE), 3) AS AVG_CONFIDENCE, SUM(CASE WHEN MATCHES_PUBLISHED THEN 1 ELSE 0 END) AS MATCHING_PUBLISHED, ROUND(AVG(ABS(NAV_VARIANCE_USD_M)), 2) AS AVG_ABS_NAV_VARIANCE_USD_M
FROM V_REPORT_EXTRACTION_RECONCILIATION
GROUP BY REVIEW_STATUS
ORDER BY EXTRACTIONS DESC""")
add_eval_only("Which extractions from the Q2 2026 reports have a NAV variance of more than 5 million against the published figures?",
    f"""SELECT FUND_NAME, STRATEGY, VINTAGE_YEAR, SOURCE_DOCUMENT, EXTRACTED_NAV_USD_M, PUBLISHED_NAV_USD_M, NAV_VARIANCE_USD_M, EXTRACTION_CONFIDENCE, REVIEW_STATUS
FROM V_REPORT_EXTRACTION_RECONCILIATION
WHERE REPORT_QUARTER_END = {LATEST} AND ABS(NAV_VARIANCE_USD_M) > 5
ORDER BY ABS(NAV_VARIANCE_USD_M) DESC""")

# ---------------------------------------------------------------- CP3: distribution drought
add("Compare median DPI at sixteen quarters of age by vintage year.",
    """SELECT VINTAGE_YEAR, COUNT(FUND_ID) AS FUND_COUNT, ROUND(MEDIAN(DPI), 3) AS MEDIAN_DPI, ROUND(MEDIAN(PAID_IN_PCT), 1) AS MEDIAN_PAID_IN_PCT, ROUND(MEDIAN(DISTRIBUTED_PCT_OF_COMMITMENT), 1) AS MEDIAN_DISTRIBUTED_PCT_OF_COMMITMENT
FROM V_CASH_FLOW_PACING_QUARTERLY
WHERE FUND_AGE_QUARTERS = 16
GROUP BY VINTAGE_YEAR
ORDER BY VINTAGE_YEAR""")
add("How much was called from and distributed to LPs across the universe each year since 2019?",
    """SELECT EXTRACT(YEAR FROM FLOW_DATE) AS FLOW_YEAR,
       ROUND(SUM(CASE WHEN FLOW_TYPE = 'CAPITAL_CALL' THEN AMOUNT_USD_M ELSE 0 END), 0) AS CAPITAL_CALLS_USD_M,
       ROUND(SUM(CASE WHEN FLOW_TYPE = 'DISTRIBUTION' THEN AMOUNT_USD_M ELSE 0 END), 0) AS DISTRIBUTIONS_USD_M,
       ROUND(SUM(CASE WHEN FLOW_TYPE = 'DISTRIBUTION' THEN AMOUNT_USD_M ELSE -AMOUNT_USD_M END), 0) AS NET_CASH_FLOW_USD_M
FROM FUND_CASH_FLOWS
WHERE FLOW_DATE >= DATE '2019-01-01'
GROUP BY EXTRACT(YEAR FROM FLOW_DATE)
ORDER BY FLOW_YEAR""")
add("What were total distributions in the first half of 2026 versus the first half of 2021?",
    """SELECT ROUND(SUM(CASE WHEN FLOW_DATE BETWEEN DATE '2021-01-01' AND DATE '2021-06-30' THEN AMOUNT_USD_M ELSE 0 END), 0) AS H1_2021_DISTRIBUTIONS_USD_M,
       ROUND(SUM(CASE WHEN FLOW_DATE BETWEEN DATE '2026-01-01' AND DATE '2026-06-30' THEN AMOUNT_USD_M ELSE 0 END), 0) AS H1_2026_DISTRIBUTIONS_USD_M,
       ROUND(100.0 * (SUM(CASE WHEN FLOW_DATE BETWEEN DATE '2026-01-01' AND DATE '2026-06-30' THEN AMOUNT_USD_M ELSE 0 END) / SUM(CASE WHEN FLOW_DATE BETWEEN DATE '2021-01-01' AND DATE '2021-06-30' THEN AMOUNT_USD_M ELSE 0 END) - 1), 1) AS CHANGE_PCT
FROM FUND_CASH_FLOWS
WHERE FLOW_TYPE = 'DISTRIBUTION'""")
add_eval_only("Show net cash flow by fund age for vintages 2021 and 2022 against vintages 2014 to 2016.",
    """SELECT FUND_AGE_QUARTERS,
       ROUND(100.0 * SUM(CASE WHEN VINTAGE_YEAR BETWEEN 2014 AND 2016 THEN NET_CASH_FLOW_USD_M END) / SUM(CASE WHEN VINTAGE_YEAR BETWEEN 2014 AND 2016 THEN FUND_SIZE_USD_M END), 2) AS NET_CASH_FLOW_PCT_2014_2016,
       ROUND(100.0 * SUM(CASE WHEN VINTAGE_YEAR BETWEEN 2021 AND 2022 THEN NET_CASH_FLOW_USD_M END) / SUM(CASE WHEN VINTAGE_YEAR BETWEEN 2021 AND 2022 THEN FUND_SIZE_USD_M END), 2) AS NET_CASH_FLOW_PCT_2021_2022,
       ROUND(MEDIAN(CASE WHEN VINTAGE_YEAR BETWEEN 2014 AND 2016 THEN DPI END), 3) AS MEDIAN_DPI_2014_2016,
       ROUND(MEDIAN(CASE WHEN VINTAGE_YEAR BETWEEN 2021 AND 2022 THEN DPI END), 3) AS MEDIAN_DPI_2021_2022
FROM V_CASH_FLOW_PACING_QUARTERLY
WHERE (VINTAGE_YEAR BETWEEN 2014 AND 2016 OR VINTAGE_YEAR BETWEEN 2021 AND 2022) AND FUND_AGE_QUARTERS <= 20
GROUP BY FUND_AGE_QUARTERS
ORDER BY FUND_AGE_QUARTERS""")

