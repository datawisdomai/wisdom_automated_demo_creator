def lineage_for(customer_name: str) -> str:
    return f"""
SELECT L.CHAIN_CONTRACT_NUMBER, L.VERSION, L.DOCUMENT_NUMBER, L.DOCUMENT_TYPE, L.SIGNED_DATE, L.EFFECTIVE_DATE, L.END_DATE, L.TCV, L.TCV_CHANGE,
       L.END_DATE_CHANGE_DAYS, L.PAYMENT_TERMS, L.BILLING_FREQUENCY, L.PRODUCT_COUNT, L.MILESTONE_COUNT, L.PRODUCT_SUMMARY, L.SPECIAL_TERMS, L.PDF_FILE_NAME,
       S.SF_VERSION_REFLECTED, S.SF_AMOUNT, S.NS_VERSION_REFLECTED, S.NS_AMOUNT, S.NS_END_DATE, S.NS_PAYMENT_TERMS, S.NS_BILLING_SCHEDULE_TYPE, S.NS_SALES_ORDER_COUNT,
       CASE WHEN L.VERSION <= COALESCE(S.SF_VERSION_REFLECTED, 0) THEN 'Yes' ELSE 'No' END AS IN_SALESFORCE,
       CASE WHEN L.VERSION <= COALESCE(S.NS_VERSION_REFLECTED, 0) THEN 'Yes' ELSE 'No' END AS IN_NETSUITE
FROM "V_AMENDMENT_LINEAGE" L
JOIN "V_CHAIN_SYSTEM_SUMMARY" S ON S.CHAIN_ID = L.CHAIN_ID
WHERE L.CUSTOMER_NAME = '{customer_name}'
ORDER BY L.CHAIN_CONTRACT_NUMBER, L.VERSION
"""


