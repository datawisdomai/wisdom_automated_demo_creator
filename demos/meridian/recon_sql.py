MISSING_BILLING_MILESTONE = f"""
SELECT CH.CHAIN_ID, CH.CONTRACT_NUMBER, CH.CUSTOMER_NAME, CH.CUSTOMER_TYPE, CH.ACCOUNT_OWNER,
       RC.CHECK_TYPE, RC.FIELD_NAME,
       'Milestone ' || CAST(M.MILESTONE_NUMBER AS VARCHAR) || ' ' || M.MILESTONE_DESCRIPTION || ' due ' || CAST(M.SCHEDULED_DATE AS VARCHAR) || ' for ' || CAST(M.SCHEDULED_AMOUNT AS VARCHAR) AS CONTRACT_VALUE,
       CAST(NULL AS VARCHAR) AS SALESFORCE_VALUE,
       'No NetSuite bill for this amount within {MILESTONE_DAYS} days' AS NETSUITE_VALUE,
       M.SCHEDULED_AMOUNT AS VARIANCE_USD,
       {_SEV.format(var='M.SCHEDULED_AMOUNT')} AS SEVERITY,
       RC.OWNING_TEAM, RC.SOX_CONTROL_REF, RC.CORRECTIVE_SYSTEM,
       'Exhibit B of the latest signed document schedules ' || CAST(M.SCHEDULED_AMOUNT AS VARCHAR) || ' on ' || CAST(M.SCHEDULED_DATE AS VARCHAR) || ' (' || M.MILESTONE_DESCRIPTION || ') but no NetSuite bill matches it' AS REASON,
       M.SCHEDULE_ID AS DETAIL_KEY,
       CH.LATEST_SIGNED_DATE, CH.AMENDMENT_COUNT, CH.CURRENT_TCV
FROM "V_CONTRACT_CHAIN" CH
JOIN "CONTRACT_BILLING_SCHEDULE" M ON M.CONTRACT_ID = CH.LATEST_CONTRACT_ID
{_CTRL.format(ct='MISSING_BILLING_MILESTONE')}
LEFT JOIN (
    SELECT DISTINCT X.CHAIN_ID, B.BILL_ID, B.BILL_DATE, B.BILL_AMOUNT
    FROM "V_DEAL_CROSSWALK" X
    JOIN "NETSUITE_BILLING_SCHEDULE" B ON B.SALES_ORDER_ID = X.SALES_ORDER_ID
    WHERE X.CHAIN_ID IS NOT NULL
) NB ON NB.CHAIN_ID = CH.CHAIN_ID
    AND DATEDIFF('day', M.SCHEDULED_DATE, NB.BILL_DATE) BETWEEN -{MILESTONE_DAYS} AND {MILESTONE_DAYS}
    AND ABS(NB.BILL_AMOUNT - M.SCHEDULED_AMOUNT) <= 1
WHERE NB.BILL_ID IS NULL
"""

CHECKS: dict[str, str] = {
    "TCV_MISMATCH": TCV_MISMATCH,
    "PRODUCT_LINE_COUNT_MISMATCH": PRODUCT_LINE_COUNT_MISMATCH,
    "OPPORTUNITY_WITHOUT_CONTRACT_LINK": OPPORTUNITY_WITHOUT_CONTRACT_LINK,
    "AMENDMENT_NOT_IN_SALESFORCE": AMENDMENT_NOT_IN_SALESFORCE,
    "TERM_END_DATE_MISMATCH": TERM_END_DATE_MISMATCH,
    "AMENDMENT_NOT_IN_NETSUITE": AMENDMENT_NOT_IN_NETSUITE,
    "DUPLICATE_SALES_ORDERS": DUPLICATE_SALES_ORDERS,
    "SALES_ORDER_WITHOUT_OPPORTUNITY": SALES_ORDER_WITHOUT_OPPORTUNITY,
    "PAYMENT_TERMS_MISMATCH": PAYMENT_TERMS_MISMATCH,
    "BILLING_FREQUENCY_MISMATCH": BILLING_FREQUENCY_MISMATCH,
    "MISSING_BILLING_MILESTONE": MISSING_BILLING_MILESTONE,
}

# the full three-way match: every finding from every check
ALL_FINDINGS = "\nUNION ALL\n".join(q.strip() for q in CHECKS.values())
FINDINGS_CTE = "WITH F AS (\n" + ALL_FINDINGS + "\n)\n"


# ---------------------------------------------------------------- compact union for roll-ups
# Same eleven checks and tolerances as above with only the columns the roll-ups need, so the
# certified query library stays small. checks.py asserts that SLIM and the full union agree.
_SLIM_COLS = "S.CHAIN_ID, S.CONTRACT_NUMBER, S.CUSTOMER_NAME, S.CUSTOMER_TYPE, S.ACCOUNT_OWNER, S.LATEST_SIGNED_DATE, S.AMENDMENT_COUNT, S.CURRENT_TCV"
SLIM_FINDINGS_CTE = f"""WITH S AS (SELECT * FROM "V_CHAIN_SYSTEM_SUMMARY"),
F0 AS (
SELECT {_SLIM_COLS}, 'TCV_MISMATCH' AS CHECK_TYPE, COALESCE(S.SF_AMOUNT, 0) - S.CURRENT_TCV AS VARIANCE_USD FROM S WHERE ABS(COALESCE(S.SF_AMOUNT, 0) - S.CURRENT_TCV) > {AMOUNT_TOL}
UNION ALL SELECT {_SLIM_COLS}, 'PRODUCT_LINE_COUNT_MISMATCH', 0 FROM S WHERE S.SF_OPPORTUNITY_COUNT > 0 AND COALESCE(S.SF_PRODUCT_COUNT, 0) <> S.CURRENT_PRODUCT_COUNT
UNION ALL SELECT {_SLIM_COLS}, 'AMENDMENT_NOT_IN_SALESFORCE', 0 FROM S WHERE S.AMENDMENT_COUNT > 0 AND COALESCE(S.SF_VERSION_REFLECTED, 0) < S.LATEST_VERSION
UNION ALL SELECT {_SLIM_COLS}, 'TERM_END_DATE_MISMATCH', 0 FROM S WHERE S.NS_SALES_ORDER_COUNT > 0 AND S.NS_END_DATE <> S.CURRENT_END_DATE
UNION ALL SELECT {_SLIM_COLS}, 'AMENDMENT_NOT_IN_NETSUITE', S.CURRENT_TCV - S.NS_AMOUNT FROM S WHERE S.AMENDMENT_COUNT > 0 AND S.NS_SALES_ORDER_COUNT > 0 AND COALESCE(S.NS_VERSION_REFLECTED, 0) < S.LATEST_VERSION
UNION ALL SELECT {_SLIM_COLS}, 'DUPLICATE_SALES_ORDERS', GREATEST(S.NS_AMOUNT - S.CURRENT_TCV, 0) FROM S WHERE S.NS_SALES_ORDER_COUNT > 1
UNION ALL SELECT {_SLIM_COLS}, 'PAYMENT_TERMS_MISMATCH', 0 FROM S WHERE S.NS_SALES_ORDER_COUNT > 0 AND S.NS_PAYMENT_TERMS <> S.CURRENT_PAYMENT_TERMS
UNION ALL SELECT {_SLIM_COLS}, 'BILLING_FREQUENCY_MISMATCH', 0 FROM S WHERE S.NS_SALES_ORDER_COUNT > 0 AND S.NS_BILLING_SCHEDULE_TYPE <> S.CURRENT_BILLING_FREQUENCY
UNION ALL SELECT CAST(NULL AS VARCHAR), COALESCE(O.LINKED_CONTRACT_NUMBER, '(no contract number)'), CU.CUSTOMER_NAME, CU.CUSTOMER_TYPE, CU.ACCOUNT_OWNER, O.CLOSE_DATE, 0, O.AMOUNT, 'OPPORTUNITY_WITHOUT_CONTRACT_LINK', O.AMOUNT
  FROM "SALESFORCE_OPPORTUNITIES" O JOIN "CUSTOMERS" CU ON CU.CUSTOMER_ID = O.CUSTOMER_ID
  LEFT JOIN "CONTRACTS" C ON C.CONTRACT_NUMBER = O.LINKED_CONTRACT_NUMBER AND C.CUSTOMER_ID = O.CUSTOMER_ID WHERE C.CONTRACT_ID IS NULL
UNION ALL SELECT S.CHAIN_ID, S.CONTRACT_NUMBER, S.CUSTOMER_NAME, S.CUSTOMER_TYPE, S.ACCOUNT_OWNER, S.LATEST_SIGNED_DATE, S.AMENDMENT_COUNT, S.CURRENT_TCV, 'SALES_ORDER_WITHOUT_OPPORTUNITY', 0
  FROM "NETSUITE_SALES_ORDERS" SO JOIN (SELECT DISTINCT SALES_ORDER_ID, CHAIN_ID FROM "V_DEAL_CROSSWALK" WHERE SALES_ORDER_ID IS NOT NULL AND CHAIN_ID IS NOT NULL) X ON X.SALES_ORDER_ID = SO.SALES_ORDER_ID
  JOIN S ON S.CHAIN_ID = X.CHAIN_ID WHERE SO.OPPORTUNITY_ID IS NULL
UNION ALL SELECT S.CHAIN_ID, S.CONTRACT_NUMBER, S.CUSTOMER_NAME, S.CUSTOMER_TYPE, S.ACCOUNT_OWNER, S.LATEST_SIGNED_DATE, S.AMENDMENT_COUNT, S.CURRENT_TCV, 'MISSING_BILLING_MILESTONE', M.SCHEDULED_AMOUNT
  FROM S JOIN "V_CONTRACT_CHAIN" CH ON CH.CHAIN_ID = S.CHAIN_ID JOIN "CONTRACT_BILLING_SCHEDULE" M ON M.CONTRACT_ID = CH.LATEST_CONTRACT_ID
  LEFT JOIN (SELECT DISTINCT X.CHAIN_ID, B.BILL_ID, B.BILL_DATE, B.BILL_AMOUNT FROM "V_DEAL_CROSSWALK" X JOIN "NETSUITE_BILLING_SCHEDULE" B ON B.SALES_ORDER_ID = X.SALES_ORDER_ID WHERE X.CHAIN_ID IS NOT NULL) NB
    ON NB.CHAIN_ID = S.CHAIN_ID AND DATEDIFF('day', M.SCHEDULED_DATE, NB.BILL_DATE) BETWEEN -{MILESTONE_DAYS} AND {MILESTONE_DAYS} AND ABS(NB.BILL_AMOUNT - M.SCHEDULED_AMOUNT) <= 1
  WHERE NB.BILL_ID IS NULL
),
F AS (
SELECT F0.*, RC.OWNING_TEAM, RC.SOX_CONTROL_REF, RC.FIELD_NAME,
       CASE WHEN RC.HIGH_SEVERITY_USD IS NOT NULL AND ABS(F0.VARIANCE_USD) >= RC.HIGH_SEVERITY_USD THEN 'High' ELSE RC.DEFAULT_SEVERITY END AS SEVERITY
FROM F0 JOIN "RECONCILIATION_CONTROLS" RC ON RC.CHECK_TYPE = F0.CHECK_TYPE
)
"""

# ---------------------------------------------------------------- roll-ups
ALL_FINDINGS_RANKED = FINDINGS_CTE + """
SELECT CHAIN_ID, CONTRACT_NUMBER, CUSTOMER_NAME, CUSTOMER_TYPE, ACCOUNT_OWNER, CHECK_TYPE, FIELD_NAME, CONTRACT_VALUE, SALESFORCE_VALUE, NETSUITE_VALUE,
       VARIANCE_USD, ABS(VARIANCE_USD) AS EXPOSURE_USD, SEVERITY, OWNING_TEAM, SOX_CONTROL_REF, CORRECTIVE_SYSTEM, REASON, DETAIL_KEY, LATEST_SIGNED_DATE, AMENDMENT_COUNT
FROM F
ORDER BY ABS(VARIANCE_USD) DESC, SEVERITY, CUSTOMER_NAME, CHECK_TYPE
"""

CHAINS_NOT_RECONCILING = SLIM_FINDINGS_CTE + """
SELECT F.CHAIN_ID, F.CONTRACT_NUMBER, F.CUSTOMER_NAME, F.CUSTOMER_TYPE, F.ACCOUNT_OWNER, MAX(F.AMENDMENT_COUNT) AS AMENDMENT_COUNT, MAX(F.CURRENT_TCV) AS CURRENT_TCV,
       COUNT(*) AS FINDINGS, COUNT(DISTINCT F.CHECK_TYPE) AS CHECKS_FAILED, SUM(ABS(F.VARIANCE_USD)) AS EXPOSURE_USD,
       SUM(CASE WHEN F.SEVERITY = 'High' THEN 1 ELSE 0 END) AS HIGH_FINDINGS,
       MIN(F.CHECK_TYPE) AS FIRST_CHECK_TYPE
FROM F
WHERE F.CHAIN_ID IS NOT NULL
GROUP BY F.CHAIN_ID, F.CONTRACT_NUMBER, F.CUSTOMER_NAME, F.CUSTOMER_TYPE, F.ACCOUNT_OWNER
ORDER BY EXPOSURE_USD DESC, FINDINGS DESC
"""

SUMMARY_TOTALS = SLIM_FINDINGS_CTE + """
SELECT COUNT(*) AS FINDINGS,
       COUNT(DISTINCT F.CHAIN_ID) AS CHAINS_WITH_FINDINGS,
       (SELECT COUNT(*) FROM "V_CONTRACT_CHAIN") AS CHAINS_CHECKED,
       ROUND(COUNT(DISTINCT F.CHAIN_ID) * 1.0 / (SELECT COUNT(*) FROM "V_CONTRACT_CHAIN"), 4) AS MISMATCH_RATE,
       SUM(ABS(F.VARIANCE_USD)) AS EXPOSURE_USD,
       SUM(CASE WHEN F.SEVERITY = 'High' THEN 1 ELSE 0 END) AS HIGH_FINDINGS,
       SUM(CASE WHEN F.SEVERITY = 'Medium' THEN 1 ELSE 0 END) AS MEDIUM_FINDINGS
FROM F
"""

BY_TEAM = SLIM_FINDINGS_CTE + """
SELECT F.OWNING_TEAM, F.SOX_CONTROL_REF, F.CHECK_TYPE, COUNT(*) AS FINDINGS, COUNT(DISTINCT F.CHAIN_ID) AS CHAINS,
       SUM(ABS(F.VARIANCE_USD)) AS EXPOSURE_USD, SUM(CASE WHEN F.SEVERITY = 'High' THEN 1 ELSE 0 END) AS HIGH_FINDINGS
FROM F
GROUP BY F.OWNING_TEAM, F.SOX_CONTROL_REF, F.CHECK_TYPE
ORDER BY F.OWNING_TEAM, EXPOSURE_USD DESC
"""

BY_TEAM_TOTALS = SLIM_FINDINGS_CTE + """
SELECT F.OWNING_TEAM, COUNT(*) AS FINDINGS, COUNT(DISTINCT F.CHAIN_ID) AS CHAINS, SUM(ABS(F.VARIANCE_USD)) AS EXPOSURE_USD,
       SUM(CASE WHEN F.SEVERITY = 'High' THEN 1 ELSE 0 END) AS HIGH_FINDINGS
FROM F
GROUP BY F.OWNING_TEAM
ORDER BY EXPOSURE_USD DESC
"""

BY_ACCOUNT_OWNER = SLIM_FINDINGS_CTE + """
SELECT C.ACCOUNT_OWNER, C.SALES_POD,
       COUNT(DISTINCT C.CHAIN_ID) AS CHAINS_OWNED,
       COUNT(DISTINCT F.CHAIN_ID) AS CHAINS_WITH_FINDINGS,
       ROUND(COUNT(DISTINCT F.CHAIN_ID) * 1.0 / COUNT(DISTINCT C.CHAIN_ID), 4) AS MISMATCH_RATE,
       COUNT(F.CHECK_TYPE) AS FINDINGS,
       COALESCE(SUM(ABS(F.VARIANCE_USD)), 0) AS EXPOSURE_USD
FROM "V_CONTRACT_CHAIN" C
LEFT JOIN F ON F.CHAIN_ID = C.CHAIN_ID
GROUP BY C.ACCOUNT_OWNER, C.SALES_POD
ORDER BY MISMATCH_RATE DESC, EXPOSURE_USD DESC
"""

